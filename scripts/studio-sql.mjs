#!/usr/bin/env node
/**
 * Writes a built-in studio's branding (src/data/studios/<slug>.ts) into supabase/seed.sql, so the live
 * database shows exactly what the demo shows.
 *
 *   node scripts/studio-sql.mjs snowy           # print the SQL
 *   node scripts/studio-sql.mjs snowy --write   # replace the block between the markers in supabase/seed.sql
 *
 * The SQL only fills a studio whose branding is still empty, so re-running the seed never overwrites changes
 * the owner made in Settings -> Branding.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [slug = 'snowy', flag] = process.argv.slice(2);

const r = await build({ entryPoints: ['src/data/studios/index.ts'], bundle: true, write: false, format: 'esm', platform: 'neutral', absWorkingDir: root, logLevel: 'silent' });
const { BUILTIN_STUDIOS } = await import('data:text/javascript;base64,' + Buffer.from(r.outputFiles[0].text).toString('base64'));
const s = BUILTIN_STUDIOS.find((x) => x.slug === slug);
if (!s) { console.error(`No built-in studio "${slug}". Known: ${BUILTIN_STUDIOS.map((x) => x.slug).join(', ')}`); process.exit(1); }

const json = JSON.stringify(s.branding);
if (json.includes('$brand$')) throw new Error('branding contains the SQL quote tag');
const lit = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const begin = `-- >>> studio ${slug} branding (generated by scripts/studio-sql.mjs from src/data/studios/${slug}.ts; edit that file and re-run)`;
const end = `-- <<< studio ${slug} branding`;
const sql = `${begin}
update public.studios
   set branding = $brand$${json}$brand$::jsonb,
       website = coalesce(website, ${lit(s.website)}),
       currency = ${lit(s.currency)}, locale = ${lit(s.locale)}, tax_id_label = ${lit(s.taxIdLabel ?? 'ABN')}, tax_name = ${lit(s.taxName ?? 'GST')}
 where slug = ${lit(slug)} and branding = '{}'::jsonb;
${end}`;

if (flag !== '--write') { console.log(sql); process.exit(0); }
const seedPath = path.join(root, 'supabase/seed.sql');
const seed = readFileSync(seedPath, 'utf8');
const i = seed.indexOf(begin.slice(0, begin.indexOf('(')));
const j = seed.indexOf(end);
const next = i >= 0 && j > i ? seed.slice(0, i) + sql + seed.slice(j + end.length) : `${seed.trimEnd()}\n\n${sql}\n`;
writeFileSync(seedPath, next);
console.log(`Updated supabase/seed.sql (${slug}: ${json.length} bytes of branding).`);
