// Momence export -> the two staging CSVs that supabase/import/momence_import.sql expects, plus a tidy-up report.
// Pure functions (no file access) so tests can feed them made-up rows. The command line wrapper is momence-convert.mts.
// Privacy: the real exports hold a studio's client data. This file never contains any; keep exports outside the repo.

export const PLACEHOLDER_DOMAIN = 'autogenerated.momence.com';
export const STUDIO_TZ = 'Australia/Sydney';

// ----------------------------------------------------------------------------- CSV
/** Parses CSV text (quotes, doubled quotes, CRLF, BOM, newlines inside quotes). Returns objects keyed by the header row. */
export function parseCsv(text: string): Record<string, string>[] {
  const s = text.replace(/^﻿/, '');
  const rows: string[][] = [];
  let row: string[] = [], cell = '', quoted = false;
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]!;
    if (quoted) {
      if (ch === '"') { if (s[i + 1] === '"') { cell += '"'; i++; } else quoted = false; } else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && s[i + 1] === '\n') i++;
      row.push(cell); cell = '';
      if (row.some((c) => c !== '')) rows.push(row);
      row = [];
    } else cell += ch;
  }
  row.push(cell);
  if (row.some((c) => c !== '')) rows.push(row);
  const head = (rows.shift() ?? []).map((h) => h.trim());
  return rows.map((r) => Object.fromEntries(head.map((h, i) => [h, (r[i] ?? '').trim()])));
}

const cell = (v: string) => (/[",\r\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
export function toCsv<T extends object>(head: readonly (keyof T & string)[], rows: readonly T[]): string {
  return [head.join(','), ...rows.map((r) => head.map((h) => cell(String((r as Record<string, unknown>)[h] ?? ''))).join(','))].join('\r\n') + '\r\n';
}

// ----------------------------------------------------------------------------- dates
const MONTHS = ['january', 'february', 'march', 'april', 'may', 'june', 'july', 'august', 'september', 'october', 'november', 'december'];

/** "December 18th 2025, 8:40 AM" (Sydney time) -> "2025-12-18". Anything else (blank, junk) -> ''. */
export function parseMomenceDate(v: string): string {
  const m = /^\s*([A-Za-z]+)\.?\s+(\d{1,2})(?:st|nd|rd|th)?,?\s+(\d{4})/.exec(v ?? '');
  if (!m) return '';
  const mi = MONTHS.findIndex((x) => x === m[1]!.toLowerCase() || x.slice(0, 3) === m[1]!.toLowerCase().slice(0, 3));
  const day = Number(m[2]);
  if (mi < 0 || day < 1 || day > 31) return '';
  return `${m[3]}-${String(mi + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
}

const sydneyParts = new Intl.DateTimeFormat('en-CA', { timeZone: STUDIO_TZ, year: 'numeric', month: '2-digit', day: '2-digit' });
/** An ISO timestamp (usually UTC, ending in Z) -> the calendar date in Sydney, "YYYY-MM-DD". Blank or junk -> ''. */
export function sydneyDate(iso: string): string {
  const t = (iso ?? '').trim();
  if (!t) return '';
  if (/^\d{4}-\d{2}-\d{2}$/.test(t)) return t;
  const d = new Date(t);
  if (Number.isNaN(d.getTime())) return '';
  return sydneyParts.format(d);
}

// ----------------------------------------------------------------------------- products
export interface ProductDef { name: string; kind: 'membership' | 'pack' | 'dropin' | 'intro'; credits: number | null }
/** Snowy's products, named as in RULES.md (which match Momence's names once case and punctuation are ignored). */
export const SNOWY_PRODUCTS: ProductDef[] = [
  { name: '1 Class Per Week Membership', kind: 'membership', credits: 1 },
  { name: '2 Classes Per Week Membership', kind: 'membership', credits: 2 },
  { name: '3 Classes Per Week Membership', kind: 'membership', credits: 3 },
  { name: 'Unlimited Membership', kind: 'membership', credits: null },
  { name: 'Single class', kind: 'dropin', credits: 1 },
  { name: '4 class pack', kind: 'pack', credits: 4 },
  { name: '8 class pack', kind: 'pack', credits: 8 },
  { name: 'Intro offer, 2 weeks unlimited', kind: 'intro', credits: null },
];

/** Lower case, punctuation and spacing ignored: "INTRO OFFER - 2 WEEKS" and "Intro offer, 2 weeks" match. */
export const normName = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

/** The product part of "<id>-ribbon-active-members-<Product_Name>.csv" ('_' -> ' ', ' - ' kept), or null if not a members file. */
export function productFromFilename(file: string): string | null {
  const base = file.split(/[\\/]/).pop() ?? file;
  const m = /ribbon-active-members-(.+?)\.csv$/i.exec(base);
  return m ? m[1]!.replace(/_/g, ' ').trim() : null;
}

// ----------------------------------------------------------------------------- converting
export interface InputFile { name: string; text: string }
export interface ConvertOptions { products?: ProductDef[]; ignore?: string[] }

export interface ClientRow { momence_id: string; first_name: string; last_name: string; email: string; phone: string; birthday: string; joined_on: string; marketing_opt_in: string; injuries: string; emergency_contact_name: string; emergency_contact_phone: string; staff_notes: string; has_purchased_before: string }
export interface PassRow { email: string; pass_name: string; kind: string; credits_total: string; credits_left: string; expires_on: string; paid_until: string; momence_id: string }
export const CLIENT_COLUMNS = ['momence_id', 'first_name', 'last_name', 'email', 'phone', 'birthday', 'joined_on', 'marketing_opt_in', 'injuries', 'emergency_contact_name', 'emergency_contact_phone', 'staff_notes', 'has_purchased_before'] as const;
export const PASS_COLUMNS = ['email', 'pass_name', 'kind', 'credits_total', 'credits_left', 'expires_on', 'paid_until', 'momence_id'] as const;

/** A membership/intro line as it came out of a members file (kept for the report). */
export interface Holding { email: string; firstName: string; lastName: string; product: ProductDef; billingOrExpiry: string; fromFile: string }
export interface CustomerLine { email: string; firstName: string; lastName: string; phone: string; firstSeen: string }

export interface Conversion {
  clients: ClientRow[];
  passes: PassRow[];
  customers: CustomerLine[];
  holdings: Holding[];
  /** emails that are in a members file but not in the customers file */
  missingFromCustomers: string[];
  stats: { customerRows: number; clients: number; passes: number; byProduct: Record<string, number>; introBlankExpiry: number; placeholderEmails: number };
}

const clean = (s: string | undefined) => (s ?? '').trim().replace(/\s+/g, ' ');
const cleanEmail = (s: string | undefined) => (s ?? '').trim().toLowerCase();
export const isPlaceholder = (email: string) => email.toLowerCase().endsWith('@' + PLACEHOLDER_DOMAIN);

/** Short stable id for a pass, so re-running the import never doubles anyone up. No personal info in it. */
export function passKey(email: string, product: string): string {
  let h1 = 0xdeadbeef ^ 0, h2 = 0x41c6ce57 ^ 0;
  const s = `${email}|${normName(product)}`;
  for (let i = 0; i < s.length; i++) { const c = s.charCodeAt(i); h1 = Math.imul(h1 ^ c, 2654435761); h2 = Math.imul(h2 ^ c, 1597334677); }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 'mom-' + (h2 >>> 0).toString(16).padStart(8, '0') + (h1 >>> 0).toString(16).padStart(8, '0');
}

export function convert(files: InputFile[], opts: ConvertOptions = {}): Conversion {
  const products = opts.products ?? SNOWY_PRODUCTS;
  const customerFiles = files.filter((f) => /momence-customers\.csv$/i.test(f.name));
  if (customerFiles.length !== 1) {
    throw new Error(customerFiles.length === 0
      ? 'Could not find the customers file (a file ending in Momence-Customers.csv).'
      : `Found ${customerFiles.length} customers files (${customerFiles.map((f) => f.name).join(', ')}); keep just one.`);
  }
  const memberFiles = files.filter((f) => productFromFilename(f.name) !== null);

  // Match every members file to a product, and list everything that doesn't match, all at once.
  const ignore = (opts.ignore ?? []).map(normName).filter(Boolean);
  const byNorm = new Map(products.map((p) => [normName(p.name), p]));
  const matched: { file: InputFile; product: ProductDef }[] = [];
  const unmatched: string[] = [];
  for (const f of memberFiles) {
    const fromName = productFromFilename(f.name)!;
    const p = byNorm.get(normName(fromName));
    if (p) matched.push({ file: f, product: p });
    else if (!ignore.some((i) => normName(fromName).includes(i))) unmatched.push(`${f.name}  (product "${fromName}")`);
  }
  if (unmatched.length) {
    throw new Error(`These members files don't match any product, so nothing was written:\n  - ${unmatched.join('\n  - ')}\n`
      + `Products I know: ${products.map((p) => p.name).join('; ')}.\n`
      + 'Fix the product name in the app (or ask Pete), or pass --ignore "<part of the name>" to leave a file out on purpose.');
  }

  // Customers
  const customers: CustomerLine[] = [];
  const clientsByEmail = new Map<string, ClientRow>();
  const customerRows = parseCsv(customerFiles[0]!.text);
  for (const r of customerRows) {
    const email = cleanEmail(r['Email']);
    const line = { email, firstName: clean(r['First Name']), lastName: clean(r['Last Name']), phone: clean(r['Phone Number']), firstSeen: parseMomenceDate(r['First Seen'] ?? '') };
    customers.push(line);
    if (!email || clientsByEmail.has(email)) continue;
    clientsByEmail.set(email, {
      momence_id: '', first_name: line.firstName, last_name: line.lastName, email, phone: line.phone, birthday: '', joined_on: line.firstSeen,
      marketing_opt_in: '', injuries: '', emergency_contact_name: '', emergency_contact_phone: '', staff_notes: '', has_purchased_before: '',
    });
  }

  // Members files
  const passes: PassRow[] = [];
  const holdings: Holding[] = [];
  const seenPass = new Set<string>();
  const missing = new Set<string>();
  const byProduct: Record<string, number> = {};
  let introBlankExpiry = 0;
  for (const { file, product } of matched) {
    for (const r of parseCsv(file.text)) {
      const email = cleanEmail(r['Email']);
      if (!email) continue;
      const first = clean(r['First Name']), last = clean(r['Last Name']);
      const raw = clean(r['Exp. / Remaining']);
      const day = sydneyDate(raw);
      holdings.push({ email, firstName: first, lastName: last, product, billingOrExpiry: day, fromFile: file.name });
      if (!clientsByEmail.has(email)) {
        missing.add(email);
        clientsByEmail.set(email, {
          momence_id: '', first_name: first, last_name: last, email, phone: '', birthday: '', joined_on: '', marketing_opt_in: '', injuries: '',
          emergency_contact_name: '', emergency_contact_phone: '', staff_notes: '', has_purchased_before: '',
        });
      }
      const key = passKey(email, product.name);
      if (seenPass.has(key)) continue; // the same person listed twice on one product
      seenPass.add(key);
      const row: PassRow = { email, pass_name: product.name, kind: product.kind, credits_total: '', credits_left: '', expires_on: '', paid_until: '', momence_id: key };
      if (product.kind === 'membership') {
        row.credits_total = product.credits == null ? '' : String(product.credits);
        row.paid_until = day; // the next billing date, so billing carries on from the same date
      } else if (product.kind === 'intro') {
        row.expires_on = day; // blank = not started yet: the 14 days start at their first booking
        if (!day) introBlankExpiry++;
        const c = clientsByEmail.get(email)!;
        c.has_purchased_before = 'yes'; // already had the intro offer
      } else {
        // Packs: not in Libby's export. Best guess at the format: a date is the expiry, a plain number is the credits left.
        row.credits_total = product.credits == null ? '' : String(product.credits);
        if (/^\d+$/.test(raw)) row.credits_left = raw; else row.expires_on = day;
      }
      passes.push(row);
      byProduct[product.name] = (byProduct[product.name] ?? 0) + 1;
    }
  }

  const clients = [...clientsByEmail.values()];
  return {
    clients, passes, customers, holdings, missingFromCustomers: [...missing],
    stats: { customerRows: customerRows.length, clients: clients.length, passes: passes.length, byProduct, introBlankExpiry, placeholderEmails: clients.filter((c) => isPlaceholder(c.email)).length },
  };
}

// ----------------------------------------------------------------------------- tidy-up report
export function editDistance(a: string, b: string): number {
  if (a === b) return 0;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) cur[j] = Math.min(prev[j]! + 1, cur[j - 1]! + 1, prev[j - 1]! + (a[i - 1] === b[j - 1] ? 0 : 1));
    prev = cur;
  }
  return prev[b.length]!;
}

export const COMMON_DOMAINS = ['gmail.com', 'hotmail.com', 'outlook.com', 'yahoo.com', 'yahoo.com.au', 'icloud.com', 'bigpond.com', 'bigpond.net.au', 'live.com', 'live.com.au', 'optusnet.com.au', 'me.com', 'hotmail.com.au', 'outlook.com.au'];
const split = (email: string) => { const i = email.lastIndexOf('@'); return i < 0 ? { local: email, domain: '' } : { local: email.slice(0, i), domain: email.slice(i + 1) }; };

export interface Person { email: string; name: string }
export interface ReportData {
  studioDomain: string;
  today: string;
  sameNameDifferentEmail: { name: string; emails: string[] }[];
  likelyTypoPairs: { a: string; b: string; why: string }[];
  likelyDomainTypos: { email: string; looksLike: string }[];
  twoMemberships: { email: string; name: string; products: string[] }[];
  missingFromCustomers: Person[];
  noPhone: number;
  studioAccounts: Person[];
  placeholderEmails: Person[];
  duplicateRowsInCustomers: string[];
  badEmails: string[];
  billingDatePassed: { email: string; name: string; product: string; date: string }[];
  introNotStarted: number;
}

export function buildReport(c: Conversion, opts: { studioDomain?: string; today?: string } = {}): ReportData {
  const studioDomain = (opts.studioDomain ?? 'snowypilatesclub.com').toLowerCase().replace(/^@/, '');
  const today = opts.today ?? new Date().toISOString().slice(0, 10);
  const nameOf = (r: { first_name: string; last_name: string }) => `${r.first_name} ${r.last_name}`.trim();
  const people: Person[] = c.clients.map((r) => ({ email: r.email, name: nameOf(r) }));

  const byName = new Map<string, Set<string>>();
  const display = new Map<string, string>();
  for (const p of people) {
    const k = normName(p.name);
    if (!k.includes(' ')) continue; // need first and last name to call it the same person
    (byName.get(k) ?? byName.set(k, new Set()).get(k)!).add(p.email);
    display.set(k, p.name);
  }
  const sameNameDifferentEmail = [...byName].filter(([, s]) => s.size > 1).map(([k, s]) => ({ name: display.get(k)!, emails: [...s].sort() }));

  const emails = people.map((p) => p.email).filter((e) => e.includes('@'));
  const likelyTypoPairs: ReportData['likelyTypoPairs'] = [];
  for (let i = 0; i < emails.length; i++) {
    for (let j = i + 1; j < emails.length; j++) {
      const a = emails[i]!, b = emails[j]!;
      if (Math.abs(a.length - b.length) > 2) continue;
      const d = editDistance(a, b);
      if (d === 0 || d > 2) continue;
      const A = split(a), B = split(b);
      if (A.local === B.local) likelyTypoPairs.push({ a, b, why: 'same name part, the ending differs slightly' });
      else if (A.domain === B.domain && Math.min(A.local.length, B.local.length) >= 6) likelyTypoPairs.push({ a, b, why: 'same ending, the name part differs slightly' });
    }
  }
  const likelyDomainTypos: ReportData['likelyDomainTypos'] = [];
  for (const e of emails) {
    const { domain } = split(e);
    if (!domain || COMMON_DOMAINS.includes(domain) || isPlaceholder(e)) continue;
    const near = COMMON_DOMAINS.find((d) => editDistance(domain, d) <= 2 && Math.abs(domain.length - d.length) <= 2);
    if (near) likelyDomainTypos.push({ email: e, looksLike: near });
  }

  const memberships = new Map<string, Set<string>>();
  for (const h of c.holdings) if (h.product.kind === 'membership') (memberships.get(h.email) ?? memberships.set(h.email, new Set()).get(h.email)!).add(h.product.name);
  const nameByEmail = new Map(people.map((p) => [p.email, p.name]));
  const twoMemberships = [...memberships].filter(([, s]) => s.size > 1).map(([email, s]) => ({ email, name: nameByEmail.get(email) ?? '', products: [...s].sort() }));

  const seen = new Set<string>(), dupRows: string[] = [];
  for (const cu of c.customers) { if (!cu.email) continue; if (seen.has(cu.email)) dupRows.push(cu.email); seen.add(cu.email); }

  return {
    studioDomain, today,
    sameNameDifferentEmail, likelyTypoPairs, likelyDomainTypos, twoMemberships,
    missingFromCustomers: c.missingFromCustomers.map((e) => ({ email: e, name: nameByEmail.get(e) ?? '' })),
    noPhone: c.clients.filter((r) => !r.phone).length,
    studioAccounts: people.filter((p) => { const d = split(p.email).domain; return d === studioDomain || d.endsWith('.' + studioDomain); }),
    placeholderEmails: people.filter((p) => isPlaceholder(p.email)),
    duplicateRowsInCustomers: dupRows,
    badEmails: c.customers.map((x) => x.email).concat(c.holdings.map((h) => h.email)).filter((e, i, all) => (!e || !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(e)) && all.indexOf(e) === i),
    billingDatePassed: c.holdings.filter((h) => h.product.kind === 'membership' && h.billingOrExpiry && h.billingOrExpiry < today)
      .map((h) => ({ email: h.email, name: nameByEmail.get(h.email) ?? '', product: h.product.name, date: h.billingOrExpiry })),
    introNotStarted: c.stats.introBlankExpiry,
  };
}

/** Counts only, safe to print: one number per kind of tidy-up item. */
export function reportCounts(r: ReportData): Record<string, number> {
  return {
    sameNameDifferentEmail: r.sameNameDifferentEmail.length,
    likelyTypoPairs: r.likelyTypoPairs.length,
    likelyDomainTypos: r.likelyDomainTypos.length,
    twoMemberships: r.twoMemberships.length,
    missingFromCustomers: r.missingFromCustomers.length,
    studioAccounts: r.studioAccounts.length,
    madeUpEmails: r.placeholderEmails.length,
    duplicateRowsInCustomers: r.duplicateRowsInCustomers.length,
    badEmails: r.badEmails.length,
    billingDatePassed: r.billingDatePassed.length,
    noPhone: r.noPhone,
  };
}

/** The report as a readable Markdown file. Contains real client details, so keep it outside the repo. */
export function renderReport(r: ReportData, c: Conversion): string {
  const out: string[] = [];
  const section = (title: string, n: number, why: string, lines: string[]) => {
    out.push(`## ${title} (${n})`, '', why, '');
    out.push(...(lines.length ? lines.map((l) => `- ${l}`) : ['- Nothing found.']), '');
  };
  const who = (p: Person) => `${p.name || '(no name)'} <${p.email}>`;
  out.push('# Momence import: tidy-up report', '',
    `Made ${r.today}. Nothing here has been merged or changed. Tidy these up in Momence (or decide to leave them) before the real import.`, '',
    `In the export: ${c.stats.customerRows} customer rows, ${c.stats.clients} clients going across, ${c.stats.passes} passes (`
    + Object.entries(c.stats.byProduct).map(([k, v]) => `${v} x ${k}`).join(', ') + ').', '');
  section('Same name, different emails', r.sameNameDifferentEmail.length, 'Could be one person with two emails. They would come across as two clients; merge or delete one in Momence first.',
    r.sameNameDifferentEmail.map((x) => `${x.name}: ${x.emails.join('  |  ')}`));
  section('Emails that look like typos of each other', r.likelyTypoPairs.length, 'Two near-identical emails (gmail vs gmqil, bigpond vs bigoond). Often one person who typed it wrong once.',
    r.likelyTypoPairs.map((x) => `${x.a}  |  ${x.b}  (${x.why})`));
  section('Email domains that look misspelt', r.likelyDomainTypos.length, 'The part after the @ is one or two letters off a common provider, so the client probably never gets email from the app.',
    r.likelyDomainTypos.map((x) => `${x.email}  (looks like ${x.looksLike})`));
  section('On two memberships at once', r.twoMemberships.length, 'Both memberships are imported and flagged in the client\'s staff notes. Decide which to keep and cancel the other in Momence.',
    r.twoMemberships.map((x) => `${x.name || '(no name)'} <${x.email}>: ${x.products.join(' + ')}`));
  section('Members missing from the customers file', r.missingFromCustomers.length, 'Active members who aren\'t in the customers export. They are added from the members file (no phone, no join date).',
    r.missingFromCustomers.map(who));
  section(`Accounts at ${r.studioDomain}`, r.studioAccounts.length, 'The studio\'s own accounts (owner, staff, tests). Probably shouldn\'t be clients; delete in Momence before export or archive after.',
    r.studioAccounts.map(who));
  section('Made-up Momence emails', r.placeholderEmails.length, `Momence invented these (@${PLACEHOLDER_DOMAIN}). They get a staff note "Needs a real email", and the app never emails them. Ask for real addresses at the desk. Leave them off the invite email.`,
    r.placeholderEmails.map(who));
  section('Same email twice in the customers file', r.duplicateRowsInCustomers.length, 'Only the first row is kept.', r.duplicateRowsInCustomers);
  section('Emails that don\'t look like emails', r.badEmails.length, 'Blank or malformed. Blank ones are skipped by the import.', r.badEmails.map((e) => e || '(blank)'));
  section('Membership billing date already passed', r.billingDatePassed.length, 'Momence says the next billing date is before the report date, so these would show as lapsed straight away. Re-export on switch day.',
    r.billingDatePassed.map((x) => `${x.name || '(no name)'} <${x.email}>: ${x.product}, ${x.date}`));
  out.push('## Counts only', '', `- Clients with no phone number: ${r.noPhone} of ${c.stats.clients}`,
    `- Intro offers not started yet (14 days begin at first booking): ${r.introNotStarted}`, '');
  return out.join('\n');
}
