import assert from 'node:assert/strict';
import { journey, clientSignInAs, studioSignInAs, T, goStudio } from './lib.mjs';
await journey('1 new client: sign up, intro offer, waiver, first class, studio roster + check-in', async (env) => {
  const c = await env.client();
  await c.getByRole('button', { name: 'Join the club' }).click();
  await c.getByLabel('First name').fill('Zara');
  await c.getByLabel('Last name').fill('Newcomer');
  await c.getByLabel('Email').fill('zara.newcomer@example.com');
  await c.getByLabel('Password').fill('correct-horse-9');
  await c.getByRole('button', { name: 'Create account' }).click();
  await c.locator('.strip-day').first().waitFor(T);
  await c.locator('.cls', { hasText: '9:30' }).click();
  await c.getByRole('button', { name: /Book this class/ }).click();
  await c.getByRole('button', { name: /See passes/ }).click();
  await c.getByRole('button', { name: /Claim your intro offer/ }).first().click();
  await c.getByRole('button', { name: /Continue to payment/ }).click();
  await c.locator('.sheet .btn.big, [role=dialog] .btn.big').last().click();
  await c.getByRole('button', { name: /Back to/ }).waitFor(T);
  await c.getByRole('button', { name: /Back to/ }).click();
  await c.getByRole('button', { name: /Book this class/ }).click();
  await c.getByLabel('Mobile').fill('0400 111 222');
  await c.getByLabel('Name').fill('Sam Newcomer');
  await c.getByLabel('Phone').fill('0400 333 444');
  await c.getByRole('button', { name: 'Continue' }).click();
  const q = (t) => c.locator('.hq', { hasText: t });
  for (const t of ['current injuries', 'pregnant', 'heart condition', 'neck or joint pain', 'advised you not to exercise']) await q(t).getByRole('radio', { name: 'No' }).click();
  await q('anything else').getByRole('radio', { name: 'Yes' }).click();
  await c.getByPlaceholder(/lower back pain/).fill('Tight hamstrings, easing back in.');
  await c.getByRole('button', { name: 'Continue' }).click();
  await c.getByRole('checkbox').check();
  await c.locator('input.sig').fill('Zara Newcomer');
  await c.getByRole('button', { name: /Sign and book my class/ }).click();
  await c.getByText(/You.re booked in/).waitFor(T);
  await c.getByText(/Booked with\s+Intro offer/).waitFor(T);
  // the pass and booking really exist on the client's side
  await c.keyboard.press('Escape');
  await c.getByRole('button', { name: 'Cancel booking' }).waitFor({ state: 'hidden', ...T });
  await c.getByRole('button', { name: 'Passes' }).click();
  await c.getByText('Intro offer, 2 weeks unlimited').first().waitFor(T);
  await c.getByRole('button', { name: 'Bookings' }).click();
  await c.getByText('Mat Essentials').first().waitFor(T);
  const s = await env.studio();
  await studioSignInAs(s, 'Libby');
  await s.locator('.today .stats').waitFor(T);
  await s.getByRole('link', { name: 'Open roster' }).click();
  const row = s.locator('.rrow', { hasText: 'Zara Newcomer' });
  await row.waitFor(T);
  await row.getByText('First class', { exact: true }).waitFor(T);
  await row.getByRole('button', { name: 'Check in Zara' }).click();
  await row.getByRole('button', { name: 'Undo check-in for Zara' }).waitFor(T);
  assert.equal(await row.getByRole('button', { name: /Undo check-in/ }).getAttribute('aria-pressed'), 'true');
});
